# Detokenise BBC BASIC II programs.
import sys
T = {0x80:'AND',0x81:'DIV',0x82:'EOR',0x83:'MOD',0x84:'OR',0x85:'ERROR',0x86:'LINE',0x87:'OFF',0x88:'STEP',0x89:'SPC',0x8A:'TAB(',0x8B:'ELSE',0x8C:'THEN',0x8E:'OPENIN',0x8F:'PTR',0x90:'PAGE',0x91:'TIME',0x92:'LOMEM',0x93:'HIMEM',0x94:'ABS',0x95:'ACS',0x96:'ADVAL',0x97:'ASC',0x98:'ASN',0x99:'ATN',0x9A:'BGET',0x9B:'COS',0x9C:'COUNT',0x9D:'DEG',0x9E:'ERL',0x9F:'ERR',0xA0:'EVAL',0xA1:'EXP',0xA2:'EXT',0xA3:'FALSE',0xA4:'FN',0xA5:'GET',0xA6:'INKEY',0xA7:'INSTR(',0xA8:'INT',0xA9:'LEN',0xAA:'LN',0xAB:'LOG',0xAC:'NOT',0xAD:'OPENUP',0xAE:'OPENOUT',0xAF:'PI',0xB0:'POINT(',0xB1:'POS',0xB2:'RAD',0xB3:'RND',0xB4:'SGN',0xB5:'SIN',0xB6:'SQR',0xB7:'TAN',0xB8:'TO',0xB9:'TRUE',0xBA:'USR',0xBB:'VAL',0xBC:'VPOS',0xBD:'CHR$',0xBE:'GET$',0xBF:'INKEY$',0xC0:'LEFT$(',0xC1:'MID$(',0xC2:'RIGHT$(',0xC3:'STR$',0xC4:'STRING$(',0xC5:'EOF',0xC6:'AUTO',0xC7:'DELETE',0xC8:'LOAD',0xC9:'LIST',0xCA:'NEW',0xCB:'OLD',0xCC:'RENUMBER',0xCD:'SAVE',0xCF:'PTR',0xD0:'PAGE',0xD1:'TIME',0xD2:'LOMEM',0xD3:'HIMEM',0xD4:'SOUND',0xD5:'BPUT',0xD6:'CALL',0xD7:'CHAIN',0xD8:'CLEAR',0xD9:'CLOSE',0xDA:'CLG',0xDB:'CLS',0xDC:'DATA',0xDD:'DEF',0xDE:'DIM',0xDF:'DRAW',0xE0:'END',0xE1:'ENDPROC',0xE2:'ENVELOPE',0xE3:'FOR',0xE4:'GOSUB',0xE5:'GOTO',0xE6:'GCOL',0xE7:'IF',0xE8:'INPUT',0xE9:'LET',0xEA:'LOCAL',0xEB:'MODE',0xEC:'MOVE',0xED:'NEXT',0xEE:'ON',0xEF:'VDU',0xF0:'PLOT',0xF1:'PRINT',0xF2:'PROC',0xF3:'READ',0xF4:'REM',0xF5:'REPEAT',0xF6:'REPORT',0xF7:'RESTORE',0xF8:'RETURN',0xF9:'RUN',0xFA:'STOP',0xFB:'COLOUR',0xFC:'TRACE',0xFD:'UNTIL',0xFE:'WIDTH',0xFF:'OSCLI'}
d = open(sys.argv[1],'rb').read(); i = 0; out = []
def ch(b): return chr(b) if 32 <= b < 127 else f'{{{b}}}'
while i + 3 < len(d) and d[i] == 0x0D and d[i+1] != 0xFF:
    num = d[i+1]*256 + d[i+2]; ln = d[i+3]; body = d[i+4:i+ln]; i += ln
    s = ''; q = False; j = 0; raw = False
    while j < len(body):
        b = body[j]
        if raw: s += ch(b)
        elif b == 0x22: q = not q; s += '"'
        elif q: s += ch(b)
        elif b == 0x8D:
            b1,b2,b3 = body[j+1:j+4]; lo = ((b1 << 2) & 0xC0) ^ b2; hi = ((b1 << 4) & 0xC0) ^ b3
            s += str(lo + hi*256); j += 3
        elif b >= 0x80:
            s += T.get(b, f'{{{b}}}')
            if b in (0xDC, 0xF4): raw = True
        else: s += ch(b)
        j += 1
    out.append(f'{num:5d} {s}')
print('\n'.join(out))
